import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(root, 'resources', 'parts');
const sourceUrl = 'https://www.spriters-resource.com/media/assets/112/114807.png?updated=1755478539';
const minAlpha = 1;
const minWidth = 10;
const minHeight = 10;
const minPixels = 70;
const maxDimension = 512;
const maxObjects = 1000;

async function getAtlas() {
  const response = await fetch(sourceUrl, {
    headers: {
      'User-Agent': 'Mozilla/5.0 (compatible; BadPiggiesObjectsBuild/1.3)',
      'Referer': 'https://www.spriters-resource.com/mobile/badpiggies/asset/114807/'
    },
    signal: AbortSignal.timeout(45000)
  });
  if (!response.ok) {
    throw new Error('Could not fetch original Bad Piggies atlas (HTTP ' + response.status + ').');
  }

  const bytes = Buffer.from(await response.arrayBuffer());
  const decoded = await sharp(bytes).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  if (decoded.info.width < 512 || decoded.info.height < 512) {
    throw new Error('Downloaded image is unexpectedly small: ' +
      decoded.info.width + 'x' + decoded.info.height + '.');
  }

  return {
    raw: decoded.data,
    width: decoded.info.width,
    height: decoded.info.height,
    sourceBytes: bytes.length
  };
}

function findComponents(raw, width, height) {
  const count = width * height;
  const labels = new Uint32Array(count);
  const queue = new Int32Array(count);
  const components = [];
  let nextLabel = 0;
  const alphaAt = (index) => raw[index * 4 + 3];

  for (let start = 0; start < count; start++) {
    if (labels[start] !== 0 || alphaAt(start) < minAlpha) continue;
    nextLabel++;
    let head = 0;
    let tail = 0;
    queue[tail++] = start;
    labels[start] = nextLabel;
    let minX = width;
    let minY = height;
    let maxX = -1;
    let maxY = -1;

    while (head < tail) {
      const index = queue[head++];
      const x = index % width;
      const y = Math.floor(index / width);
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;

      // Inline neighbor tests avoid millions of short-lived arrays on the atlas.
      if (x > 0) {
        const n = index - 1;
        if (labels[n] === 0 && alphaAt(n) >= minAlpha) {
          labels[n] = nextLabel;
          queue[tail++] = n;
        }
      }
      if (x + 1 < width) {
        const n = index + 1;
        if (labels[n] === 0 && alphaAt(n) >= minAlpha) {
          labels[n] = nextLabel;
          queue[tail++] = n;
        }
      }
      if (y > 0) {
        const n = index - width;
        if (labels[n] === 0 && alphaAt(n) >= minAlpha) {
          labels[n] = nextLabel;
          queue[tail++] = n;
        }
      }
      if (y + 1 < height) {
        const n = index + width;
        if (labels[n] === 0 && alphaAt(n) >= minAlpha) {
          labels[n] = nextLabel;
          queue[tail++] = n;
        }
      }
    }

    const w = maxX - minX + 1;
    const h = maxY - minY + 1;
    if (w >= minWidth && h >= minHeight && tail >= minPixels &&
        w <= maxDimension && h <= maxDimension) {
      components.push({
        label: nextLabel, x: minX, y: minY, width: w, height: h, pixels: tail
      });
    }
  }

  components.sort((a, b) => a.y - b.y || a.x - b.x || b.pixels - a.pixels);
  return { labels, components: components.slice(0, maxObjects) };
}

function generatedSource(count) {
  const lines = [
    '#include <Geode/Geode.hpp>',
    '#include <smjs.object-collab/include/object_collab.hpp>',
    '',
    'using namespace geode::prelude;',
    'using namespace object_collab::prelude;',
    '',
    '// Generated by tools/extract-original-parts.mjs. Do not edit by hand.',
    '$on_mod(Loaded) {',
    '    if (!Mod::get()->getSettingValue<bool>("show-original-parts")) return;',
    '    // ' + count + ' original atlas regions are registered below.'
  ];

  for (let i = 1; i <= count; i++) {
    const num = String(i).padStart(3, '0');
    lines.push(
      '    ObjectAPI::registerObject(ObjectInfo::builder()',
      '        .id("bp-object-' + num + '"_spr)',
      '        .sprite("bp-original-' + num + '.png"_spr)',
      '        .construction(QuickObject::builder()',
      '            .objectType(GameObjectType::Decoration)',
      '            .defaultZLayer(ZLayer::Default)',
      '            .defaultZOrder(2)',
      '            .build())',
      '        .editorTab(EditorTab::Solids)',
      '        .build());'
    );
  }

  lines.push('}', '');
  return lines.join('\n');
}

async function main() {
  await fs.mkdir(outputDir, { recursive: true });
  for (const name of await fs.readdir(outputDir)) {
    if (name.toLowerCase().endsWith('.png')) {
      await fs.unlink(path.join(outputDir, name));
    }
  }

  const atlas = await getAtlas();
  const result = findComponents(atlas.raw, atlas.width, atlas.height);
  const labels = result.labels;
  const components = result.components;
  if (components.length < 20) {
    throw new Error('Only ' + components.length + ' independent regions were found in ' +
      atlas.width + 'x' + atlas.height + '; refusing to generate a broken mod.');
  }

  const manifest = [];
  for (let i = 0; i < components.length; i++) {
    const part = components[i];
    const num = String(i + 1).padStart(3, '0');
    const rgba = Buffer.alloc(part.width * part.height * 4);

    for (let yy = 0; yy < part.height; yy++) {
      for (let xx = 0; xx < part.width; xx++) {
        const srcIndex = (part.y + yy) * atlas.width + part.x + xx;
        if (labels[srcIndex] !== part.label) continue;
        const from = srcIndex * 4;
        const to = (yy * part.width + xx) * 4;
        atlas.raw.copy(rgba, to, from, from + 4);
      }
    }

    const fileName = 'bp-original-' + num + '.png';
    await sharp(rgba, {
      raw: { width: part.width, height: part.height, channels: 4 }
    }).png({ compressionLevel: 9, adaptiveFiltering: true })
      .toFile(path.join(outputDir, fileName));

    manifest.push({
      id: 'bp-object-' + num,
      file: 'parts/' + fileName,
      originalAtlasRect: [part.x, part.y, part.width, part.height],
      visiblePixelCount: part.pixels,
      spriteSize: [part.width, part.height]
    });
  }

  await fs.writeFile(
    path.join(root, 'src', 'generated_parts.cpp'),
    generatedSource(manifest.length)
  );
  await fs.writeFile(path.join(root, 'original_parts_manifest.json'), JSON.stringify({
    source: sourceUrl.split('?')[0],
    atlasSize: [atlas.width, atlas.height],
    originalAtlasBytes: atlas.sourceBytes,
    count: manifest.length,
    extraction: 'Connected transparent-background components; original pixel colors and alpha are preserved.',
    parts: manifest
  }, null, 2));
  console.log('Generated ' + manifest.length +
    ' sprite crops and Object-Collab registrations from the original atlas (' +
    atlas.width + 'x' + atlas.height + ').');
}

main().catch((error) => {
  console.error(error && error.stack ? error.stack : String(error));
  process.exitCode = 1;
});
